#!/usr/bin/env bash
# ==============================================================================
#  سامانه یکپارچه حسابداری و مدیریت کسب‌وکار مهرگان
#  اجراکننده خودکار لینوکس و مک (Linux & macOS 1-Click Launcher)
# ==============================================================================

set -e

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$SCRIPT_DIR"

echo "=============================================================================="
echo "   به سامانه یکپارچه حسابداری و مدیریت مالی مهرگان خوش آمدید"
echo "=============================================================================="
echo ""

# 1. بررسی Node.js
if ! command -v node >/dev/null 2>&1; then
    echo "❌ [خطا] Node.js روی سیستم شما یافت نشد."
    echo "لطفاً برای اجرای برنامه، Node.js نسخه LTS را از https://nodejs.org نصب فرمایید."
    exit 1
fi

echo "✅ [1/4] محیط Node.js شناسایی شد: $(node -v)"

# 2. بررسی node_modules
if [ ! -d "$SCRIPT_DIR/node_modules" ]; then
    echo "📦 [2/4] در حال نصب خودکار وابستگی‌های برنامه (npm install)..."
    npm install
else
    echo "✅ [2/4] بسته‌های پیش‌نیاز موجود هستند."
fi

# 3. بررسی بیلد فرانت‌اند
if [ ! -f "$SCRIPT_DIR/dist/index.html" ]; then
    echo "⚙️ [3/4] در حال کامپایل و بیلد رابط کاربری فرانت‌اند..."
    npm run build
else
    echo "✅ [3/4] فایل‌های رابط کاربری آماده است."
fi

# 4. اجرای سرور
PORT="${PORT:-3000}"
export PORT

echo ""
echo "🚀 [4/4] در حال راه‌اندازی سرور مرکزی روی پورت $PORT..."
echo "=============================================================================="
echo " اطلاعات ورود به سامانه:"
echo " ----------------------------------------------------------------------------"
echo " * آدرس سیستم:              http://localhost:$PORT"
echo " * حساب مدیر سیستم:         نام کاربری: admin        |  رمز: admin"
echo " * حساب نصاب نمونه:         نام کاربری: installer_ali |  رمز: ali@123"
echo ""
echo " برای توقف برنامه کلیدهای Ctrl + C را فشار دهید."
echo "=============================================================================="
echo ""

# باز کردن خودکار مرورگر
(
    sleep 2
    if command -v xdg-open >/dev/null 2>&1; then
        xdg-open "http://localhost:$PORT" >/dev/null 2>&1 || true
    elif command -v open >/dev/null 2>&1; then
        open "http://localhost:$PORT" >/dev/null 2>&1 || true
    fi
) &

npm start
